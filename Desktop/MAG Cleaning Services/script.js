document.querySelectorAll('.lang-btn').forEach(btn => {
  btn.addEventListener('click', () => {
    applyLanguage(btn.getAttribute('data-lang'));
  });
});

/* ===== SCROLL REVEAL ===== */
const revealObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry, i) => {
    if (entry.isIntersecting) {
      setTimeout(() => entry.target.classList.add('visible'), i * 80);
      revealObserver.unobserve(entry.target);
    }
  });
}, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });

document.querySelectorAll('.reveal').forEach(el => revealObserver.observe(el));

/* ===== PRICE CALCULATOR ===== */
const basePrices = { residential: 350, deep: 800, move: 600 };
const roomMultiplier = { 1: 1, 2: 1.4, 3: 1.8, 4: 2.2, 5: 2.6 };
const extraPrices = { windows: 150, fridge: 100, oven: 80 };

let calcState = {
  step: 1,
  type: 'residential',
  rooms: 1,
  extras: []
};

function calcPrice() {
  const base = basePrices[calcState.type] || 350;
  const mult = roomMultiplier[calcState.rooms] || 1;
  const extrasTotal = calcState.extras.reduce((sum, e) => sum + (extraPrices[e] || 0), 0);
  return Math.round(base * mult + extrasTotal);
}

function updatePriceDisplay() {
  const el = document.getElementById('priceDisplay');
  if (!el) return;
  const price = calcPrice();
  el.style.transform = 'scale(1.1)';
  el.textContent = price + ' MDL';
  setTimeout(() => { el.style.transform = 'scale(1)'; }, 200);
}

function goToStep(step) {
  calcState.step = step;
  document.querySelectorAll('.calc-panel').forEach((panel, i) => {
    panel.classList.toggle('active', i + 1 === step);
  });
  document.querySelectorAll('.calc-step').forEach((s, i) => {
    s.classList.remove('active', 'done');
    if (i + 1 === step) s.classList.add('active');
    else if (i + 1 < step) s.classList.add('done');
  });
  if (step === 3) updatePriceDisplay();
}

document.querySelectorAll('.calc-next').forEach(btn => {
  btn.addEventListener('click', () => {
    if (calcState.step < 3) goToStep(calcState.step + 1);
  });
});
document.querySelectorAll('.calc-back').forEach(btn => {
  btn.addEventListener('click', () => {
    if (calcState.step > 1) goToStep(calcState.step - 1);
  });
});

document.querySelectorAll('input[name="clean_type"]').forEach(radio => {
  radio.addEventListener('change', () => {
    calcState.type = radio.value;
    updatePriceDisplay();
  });
});

document.querySelectorAll('.room-btn').forEach(btn => {
  btn.addEventListener('click', () => {
    document.querySelectorAll('.room-btn').forEach(b => b.classList.remove('selected'));
    btn.classList.add('selected');
    calcState.rooms = parseInt(btn.dataset.rooms) || 5;
    updatePriceDisplay();
  });
});
document.querySelector('.room-btn')?.classList.add('selected');

document.querySelectorAll('input[name="extra"]').forEach(cb => {
  cb.addEventListener('change', () => {
    calcState.extras = Array.from(
      document.querySelectorAll('input[name="extra"]:checked')
    ).map(c => c.value);
    updatePriceDisplay();
  });
});

